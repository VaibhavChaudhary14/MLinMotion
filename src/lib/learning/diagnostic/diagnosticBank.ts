export function getDiagnosticQuestionById(id: string): DiagnosticQuestion | undefined {
  return DIAGNOSTIC_QUESTION_BANK.find((q) => q.id === id);
}

export function getDiagnosticQuestionsByConcept(conceptId: string): DiagnosticQuestion[] {
  return DIAGNOSTIC_QUESTION_BANK.filter(
    (q) => q.conceptId === conceptId || q.secondaryConceptIds?.includes(conceptId)
  );
}

export function getDiagnosticQuestionsBySubject(subject: string): DiagnosticQuestion[] {
  return DIAGNOSTIC_QUESTION_BANK.filter((q) => q.subject === subject);
}

export function getGatePyqQuestions(): DiagnosticQuestion[] {
  return DIAGNOSTIC_QUESTION_BANK.filter((q) => q.isGatePyq);
}
